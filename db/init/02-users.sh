#!/bin/bash
set -euo pipefail
mysql --protocol=socket -uroot -p"${MYSQL_ROOT_PASSWORD}" <<SQL
CREATE USER IF NOT EXISTS '${NEWSDB_APP_USER}'@'%' IDENTIFIED BY '${NEWSDB_APP_PASSWORD}';
CREATE USER IF NOT EXISTS '${NEWSDB_RO_USER}'@'%'  IDENTIFIED BY '${NEWSDB_RO_PASSWORD}';
GRANT SELECT, INSERT, UPDATE ON newsdb.* TO '${NEWSDB_APP_USER}'@'%';
GRANT SELECT ON newsdb.* TO '${NEWSDB_RO_USER}'@'%';
FLUSH PRIVILEGES;
SQL
